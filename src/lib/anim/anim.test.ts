import { describe, expect, it } from "vitest";
import type { Animation, Stop } from "../api";
import builtins from "../mock/builtins.json";
import { compat, isCompatible, nameIndex, refMaker, resolveRef } from "./ref";
import { sampleStops } from "./palette";
import { flatten, renderAnimation } from "./render";

const names = ["Key: Q", "Key: W", "", "Key: E", "Dup", "Dup"];
const base = { schema_version: 1, id: "t", name: "t", tags: [], created: 0, updated: 1, target: { kind: "any" as const }, builtin: false };
const frames = (fr: Animation["kind"] & { type: "frames" }): Animation => ({ ...base, kind: fr });
const pos = (n: number): [number, number][] => Array.from({ length: n }, (_, i) => [i / n, 0.5]);

describe("LED references", () => {
  it("use names when unique and indices otherwise", () => {
    const ref = refMaker(names);
    expect(ref(1)).toBe("name:Key: W");
    expect(ref(2)).toBe("idx:2");
    expect(ref(4)).toBe("idx:4");
    const idx = nameIndex(names);
    expect(resolveRef("name:Key: E", idx, names.length)).toBe(3);
    expect(resolveRef("idx:5", idx, names.length)).toBe(5);
    expect(resolveRef("idx:6", idx, names.length)).toBeNull();
    expect(resolveRef("name:Nope", idx, names.length)).toBeNull();
    expect(resolveRef("junk", idx, names.length)).toBeNull();
  });

  it("report compatibility with another keyboard", () => {
    const a = frames({ type: "frames", frames: [{ leds: { "name:Key: W": [255, 0, 0] } }, { leds: { "idx:2": [0, 255, 0], "name:Key: Missing": [1, 1, 1] } }], frame_ms: 100, loop: "loop", crossfade: 0 });
    expect(compat(a, ["", "Key: W", "Key: Q"])).toEqual({ ok: 2, total: 3 });
    expect(isCompatible(a, ["", "Key: W", "Key: Q"])).toBe(true);
    expect(isCompatible(a, ["x", "y"])).toBe(false);
    const effect = builtins.find((b) => b.id === "builtin:rainbow") as Animation;
    expect(compat(effect, ["x"])).toEqual({ ok: 0, total: 0 });
    expect(isCompatible(effect, ["x"])).toBe(true);
  });
});

describe("renderer parity with effects.rs", () => {
  it("plays frames in order, loops and ping-pongs", () => {
    const mk = (mode: "loop" | "pingpong" | "once") =>
      frames({ type: "frames", frames: [0, 1, 2].map((i) => ({ leds: { [`idx:${i}`]: [1, 1, 1] as [number, number, number] } })), frame_ms: 100, loop: mode, crossfade: 0 });
    const lit = (mode: "loop" | "pingpong" | "once", t: number) => renderAnimation(mk(mode), t, ["", "", ""], pos(3)).findIndex((p) => p[3] > 0);
    expect([0.05, 0.15, 0.25, 0.35].map((t) => lit("loop", t))).toEqual([0, 1, 2, 0]);
    expect([0.05, 0.15, 0.25, 0.35, 0.45, 0.55].map((t) => lit("pingpong", t))).toEqual([0, 1, 2, 1, 0, 1]);
    expect(lit("once", 9)).toBe(2);
  });

  it("cross-fades between frames", () => {
    const a = frames({
      type: "frames",
      frames: [{ leds: { "idx:0": [200, 0, 0] }, duration_ms: 400 }, { leds: { "idx:0": [0, 0, 200], "idx:1": [0, 200, 0] }, duration_ms: 100 }],
      frame_ms: 100,
      loop: "loop",
      crossfade: 1,
    });
    const mid = renderAnimation(a, 0.2, ["", ""], pos(2));
    expect(mid[0][0]).toBeCloseTo(100, 0);
    expect(mid[0][2]).toBeCloseTo(100, 0);
    expect(mid[1][3]).toBeCloseTo(0.5, 2);
  });

  it("moves a path segment in stroke order", () => {
    const pal: Stop[] = [{ pos: 0, color: [255, 255, 255] }, { pos: 1, color: [255, 255, 255] }];
    const a: Animation = { ...base, kind: { type: "path", path: ["idx:3", "idx:1", "idx:0", "idx:2"], palette: pal, speed: 1, length: 0.25, gap: 0.75, reverse: false, tail_fade: 0 } };
    const lit = (t: number) => renderAnimation(a, t, ["", "", "", "", ""], pos(5)).findIndex((p) => p[3] > 0);
    expect([0.03, 0.28, 0.53, 0.78].map(lit)).toEqual([3, 1, 0, 2]);
  });

  it("cycles a palette without moving cells", () => {
    const pal: Stop[] = [{ pos: 0, color: [255, 0, 0] }, { pos: 0.5, color: [0, 255, 0] }, { pos: 1, color: [255, 0, 0] }];
    const a: Animation = { ...base, kind: { type: "palette", cells: { "idx:0": 0, "idx:1": 0.5 }, palette: pal, speed: 1, reverse: false } };
    const at = (t: number) => renderAnimation(a, t, ["", "", ""], pos(3));
    expect(at(0)[0].slice(0, 2)).toEqual([255, 0]);
    expect(at(0)[1].slice(0, 2)).toEqual([0, 255]);
    expect(at(0)[2][3]).toBe(0);
    expect(at(0.5)[0].slice(0, 2)).toEqual([0, 255]);
  });

  it("samples cyclic palettes through the seam", () => {
    const stops: Stop[] = [{ pos: 0.2, color: [0, 0, 0] }, { pos: 0.8, color: [60, 0, 0] }];
    expect(sampleStops(stops, 0, false)).toEqual([0, 0, 0]);
    expect(sampleStops(stops, 1, true)[0]).toBeCloseTo(30);
    expect(sampleStops(stops, 0.5, true)[0]).toBeCloseTo(30);
  });
});

describe("built-in presets (fixture generated by the Rust tests)", () => {
  const kb = ["`", "1", "2", "3", "4", "5", "6", "7", "8", "9", "0", "-", "=", "Q", "W", "E", "R", "T", "Y", "U", "I", "O", "P", "[", "]", "A", "S", "D", "F", "G", "H", "J", "K", "L", ";", "'", "Z", "X", "C", "V", "B", "N", "M", ",", ".", "/", "Space"].map((k) => `Key: ${k}`);
  it("render something on a standard keyboard at any time", () => {
    expect(builtins.length).toBe(9);
    for (const b of builtins as Animation[]) {
      let seen = false;
      for (const t of [0.05, 0.1, 0.3, 0.7, 1.9]) {
        const out = flatten(renderAnimation(b, t, kb, pos(kb.length)));
        seen ||= out.some((c) => c[0] + c[1] + c[2] > 0);
        for (const c of out) for (const v of c) expect(v >= 0 && v <= 255).toBe(true);
      }
      expect(seen, `${b.name} draws something`).toBe(true);
      expect(compat(b, kb).ok).toBe(compat(b, kb).total);
    }
  });
});

import { cellsToKind, framesToKind, kindToCells, kindToFrames, kindToPath, pathToKind, blankPaint } from "./draft";

describe("editor drafts", () => {
  const kbA = ["Key: Q", "Key: W", "", "Key: E"];
  const kbB = ["Key: E", "Key: W"]; // another keyboard: fewer keys, different order

  it("round-trip frames through references and survive another layout", () => {
    const leds = blankPaint(4);
    leds[1] = [255, 0, 0]; // W
    leds[2] = [0, 255, 0]; // unnamed LED 2
    const kind = framesToKind([{ id: 1, leds, ms: 120 }, { id: 2, leds: blankPaint(4), ms: null }], kbA, { frameMs: 100, loop: "loop", crossfade: 0.5 });
    expect(kind.type === "frames" && Object.keys(kind.frames[0].leds).sort()).toEqual(["idx:2", "name:Key: W"]);
    expect(kind.type === "frames" && kind.frames[0].duration_ms).toBe(120);
    expect(kind.type === "frames" && "duration_ms" in kind.frames[1]).toBe(false);
    if (kind.type !== "frames") throw new Error();
    const same = kindToFrames(kind, kbA);
    expect(same.lost).toBe(0);
    expect(same.frames[0].leds[1]).toEqual([255, 0, 0]);
    const other = kindToFrames(kind, kbB);
    expect(other.frames[0].leds[1]).toEqual([255, 0, 0]); // W moved to index 1
    expect(other.lost).toBe(1); // idx:2 does not exist there
    expect(other.frames[0].leds.length).toBe(2);
  });

  it("keeps the stroke order of a path and reports what a layout lacks", () => {
    const kind = pathToKind([3, 1, 0], kbA, { palette: [{ pos: 0, color: [1, 2, 3] }], speed: 0.5, length: 0.3, gap: 0.3, reverse: false, tail: 0.5 });
    if (kind.type !== "path") throw new Error();
    expect(kind.path).toEqual(["name:Key: E", "name:Key: W", "name:Key: Q"]);
    expect(kindToPath(kind, kbA)).toEqual({ path: [3, 1, 0], lost: 0 });
    expect(kindToPath(kind, kbB)).toEqual({ path: [0, 1], lost: 1 }); // E, W exist; Q does not
  });

  it("round-trips palette cells", () => {
    const kind = cellsToKind({ 1: 0.25, 3: 1 }, kbA, { palette: [{ pos: 0, color: [1, 2, 3] }], speed: 0.3, reverse: false });
    if (kind.type !== "palette") throw new Error();
    expect(kindToCells(kind, kbA)).toEqual({ cells: { 1: 0.25, 3: 1 }, lost: 0 });
    expect(kindToCells(kind, kbB)).toEqual({ cells: { 1: 0.25, 0: 1 }, lost: 0 });
  });
});
